"""Extract the pinned stb layout-counting pass; never modify the dependency."""
import argparse
import hashlib
from pathlib import Path

PIN = 'b04df6aa2fdd476ebcddcafd8e634014e34d29f89f6b648b137f2efa66f3bd47'

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--header',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--check',action='store_true')
    a=p.parse_args();raw=a.header.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=PIN:raise RuntimeError('stb changed; re-audit layout extraction')
    text=raw.decode()
    def extract(signature):
        start=text.index(signature);body=text.index('{',start);end=body+1;depth=1
        while depth:
            depth+=(text[end]=='{')-(text[end]=='}');end+=1
        return text[start:end]
    layout=extract('static stbir__info * stbir__alloc_internal_mem_and_build_samplers(')
    layout=layout.replace('stbir__alloc_internal_mem_and_build_samplers','c2_query_layout',1)
    def insert_before(anchor,code):
        nonlocal layout
        assert layout.count(anchor)==1
        layout=layout.replace(anchor,code+anchor)
    insert_before('      STBIR__NEXT_PTR( info->split_info[i].decode_buffer,',
        '      if (!info) static_cast<C2LayoutQuery*>(user_data)->mutable_begin = (((size_t)advance_mem)+15)&~size_t(15);\n')
    insert_before('    STBIR__NEXT_PTR( info->horizontal.contributors,',
        '    if (!info) static_cast<C2LayoutQuery*>(user_data)->mutable_end = (((size_t)advance_mem)+15)&~size_t(15);\n')
    anchor='      alloced = STBIR_MALLOC( alloced_total, user_data );'
    assert layout.count(anchor)==1
    layout=layout.replace(anchor,
        '      auto& query = *static_cast<C2LayoutQuery*>(user_data);\n'
        '      query.total = alloced_total; query.columns = sizes.num_column_slices; query.splits = splits;\n'
        '      return nullptr; // Stop after the original counting pass, before any allocation.\n')
    build=extract('static int stbir__perform_build(').replace('stbir__perform_build','c2_query_build',1)
    assert build.count('stbir__alloc_internal_mem_and_build_samplers(')==1
    build=build.replace('stbir__alloc_internal_mem_and_build_samplers(','c2_query_layout(')
    license_text=text[text.rfind('/*'):]
    assert 'ALTERNATIVE' in license_text
    result=('// Generated by tests/c2_stream/generate_size_query.py from locked stb SHA256 '+PIN+'\n'
        '// Preserves the original first layout pass without allocating memory.\n'
        '#if defined(STBIR__SEPARATE_ALLOCATIONS) || defined(STBIR_PROFILE)\n#error C2 size query requires the audited single-allocation, non-profile configuration\n#endif\n'
        'struct C2LayoutQuery { size_t total=0, mutable_begin=0, mutable_end=0; int columns=0, splits=0; };\n'
        +layout+'\n'+build+'\n'+license_text).replace('\r\n','\n')
    if a.check:
        if a.output.read_text(encoding='utf-8')!=result:raise RuntimeError('generated layout differs; re-run extraction and review diff')
    else:a.output.write_text(result,encoding='utf-8',newline='\n')

if __name__=='__main__':main()
